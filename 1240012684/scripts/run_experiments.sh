#!/usr/bin/env bash
# Full replication experiment.  Run from any directory; all paths are
# resolved relative to this script.  Requires: bash, go >= 1.20, coreutils,
# git (only for the provenance record), python3 (for analyze.py).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

REPEAT="${REPEAT:-10}"
TIMEOUT_SEC="${TIMEOUT_SEC:-5s}"
MODES=(buggy move select live)
OUT="$ROOT/results"
RAW="$OUT/raw"
mkdir -p "$ROOT/bin" "$RAW" "$OUT/figures"

export GOPROXY=off GOSUMDB=off GOTRACEBACK=all
# Leave GOMAXPROCS at the runtime default unless the caller set it explicitly.
if [ -n "${GOMAXPROCS:-}" ]; then export GOMAXPROCS; fi

echo "[setup] building repro (offline, vendored BoltDB)"
go build -o "$ROOT/bin/repro" ./cmd/repro

# ---------------------------------------------------------------- provenance
{
  echo "# Experiment provenance - generated by scripts/run_experiments.sh"
  echo "utc_started=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "repeat_per_mode=$REPEAT"
  echo "timeout=$TIMEOUT_SEC"
  echo "modes=${MODES[*]}"
  echo "go_version=$(go version)"
  echo "go_GOOS=$(go env GOOS) go_GOARCH=$(go env GOARCH)"
  echo "GOMAXPROCS_env=${GOMAXPROCS:-unset}"
  echo "kernel=$(uname -r)"
  echo "os=$(. /etc/os-release && echo "$PRETTY_NAME")"
  echo "cpu=$(lscpu | awk -F: '/Model name/ {gsub(/^ +/,"",$2); print $2; exit}')"
  echo "logical_cpus=$(nproc)"
  echo "memory_total=$(free -b | awk '/^Mem:/ {print $2}')"
  echo "gcc=$(gcc --version 2>/dev/null | head -1 || echo none)"
  echo "boltdb_commit=$(cat third_party/bolt/UPSTREAM_COMMIT.txt)"
  echo "boltdb_db_go_sha256=$(sha256sum third_party/bolt/db.go | awk '{print $1}')"
  echo "repro_binary_sha256=$(sha256sum bin/repro | awk '{print $1}')"
  echo "workload_keys=512 value_bytes=4096 initial_mmap_size=32768"
  echo "live_ticker_ms=50"
} > "$OUT/environment.txt"

# ---------------------------------------------------------------- experiment
CSV="$OUT/summary.csv"
echo "mode,run,exit_code,wall_clock_ms,deadlock_reported,timed_out,last_trace_ms,result_line,log_file" > "$CSV"

for mode in "${MODES[@]}"; do
  for i in $(seq -w 1 "$REPEAT"); do
    run_id="${mode}-${i}"
    log="$RAW/${run_id}.log"
    t0=$(date +%s%N)
    set +e
    timeout "$TIMEOUT_SEC" ./bin/repro -mode="$mode" -run-id="$run_id" > "$log" 2>&1
    rc=$?
    set -e
    t1=$(date +%s%N)
    wall_ms=$(( (t1 - t0) / 1000000 ))

    if grep -q "all goroutines are asleep - deadlock" "$log"; then det=1; else det=0; fi
    if [ "$rc" -eq 124 ] || [ "$rc" -eq 137 ]; then to=1; else to=0; fi
    # The buggy program dies inside db.View, so it never prints a [result]
    # line. `|| true` keeps pipefail from aborting the whole experiment.
    last_trace=$(grep -o 't_ms=[0-9.]*' "$log" | tail -1 | cut -d= -f2 || true)
    result_line=$(grep '^\[result\]' "$log" | tail -1 | tr -d '\r' || true)
    if [ -z "$last_trace" ]; then last_trace="NA"; fi
    if [ -z "$result_line" ]; then result_line="NA"; fi

    echo "$mode,$i,$rc,$wall_ms,$det,$to,$last_trace,\"$result_line\",results/raw/${run_id}.log" >> "$CSV"
    printf "  %-7s run %-3s rc=%-4s wall=%-6sms detected=%s timed_out=%s\n" \
      "$mode" "$i" "$rc" "$wall_ms" "$det" "$to"
  done
done

echo "[done] raw logs: $RAW ; summary: $CSV"
echo "gomaxprocs_runtime=$(grep -m1 -o 'gomaxprocs=[0-9]*' "$RAW/buggy-01.log" | cut -d= -f2)" >> "$OUT/environment.txt"
python3 scripts/analyze.py
bash scripts/race_check.sh
