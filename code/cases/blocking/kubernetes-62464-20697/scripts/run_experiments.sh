#!/usr/bin/env bash
# Batch runner for the two minimal Kubernetes blocking-bug reproductions.
# Run from any directory; all paths are relative to this script.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

REPEAT="${REPEAT:-20}"
TIMEOUT_SEC="${TIMEOUT_SEC:-5s}"
OUT="$ROOT/results"
RAW="$OUT/raw"
mkdir -p "$ROOT/bin" "$RAW"
export GOPROXY=off GOSUMDB=off GOTRACEBACK=all

BUGS=(double-rlock miss-unlock)
MODES=(buggy fixed)

echo "[setup] building repro (pure Go standard library, offline)"
go build -o "$ROOT/bin/repro" ./cmd/repro

{
  echo "# Experiment provenance - generated by scripts/run_experiments.sh"
  echo "utc_started=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "repeat_per_group=$REPEAT"
  echo "timeout=$TIMEOUT_SEC"
  echo "go_version=$(go version)"
  echo "kernel=$(uname -r)"
  echo "os=$(. /etc/os-release && echo "$PRETTY_NAME")"
  echo "cpu=$(lscpu | awk -F: '/Model name/ {gsub(/^ +/,"",$2); print $2; exit}')"
  echo "logical_cpus=$(nproc)"
  echo "GOTRACEBACK=$GOTRACEBACK"
  echo "bug_double_rlock_commit=c1b19fce903675b82e9fdd1befcc5f5d658bfe78"
  echo "bug_miss_unlock_commit=d3639aff7397dd0f0d3553b82043401ff834a356"
  echo "repro_binary_sha256=$(sha256sum bin/repro | awk '{print $1}')"
} > "$OUT/environment.txt"

CSV="$OUT/summary.csv"
echo "bug,mode,run,exit_code,wall_clock_ms,deadlock_reported,timed_out,result_line,log_file" > "$CSV"

for bug in "${BUGS[@]}"; do
  for mode in "${MODES[@]}"; do
    for i in $(seq -w 1 "$REPEAT"); do
      run_id="${bug}-${mode}-${i}"
      log="$RAW/${run_id}.log"
      t0=$(date +%s%N)
      set +e
      timeout "$TIMEOUT_SEC" ./bin/repro -bug="$bug" -mode="$mode" -run-id="$run_id" > "$log" 2>&1
      rc=$?
      set -e
      t1=$(date +%s%N)
      wall_ms=$(( (t1 - t0) / 1000000 ))

      if grep -q "all goroutines are asleep - deadlock" "$log"; then det=1; else det=0; fi
      if [ "$rc" -eq 124 ] || [ "$rc" -eq 137 ]; then to=1; else to=0; fi
      result_line=$(grep '^\[result\]' "$log" | tail -1 | tr -d '\r' || true)
      if [ -z "$result_line" ]; then result_line="NA"; fi

      echo "$bug,$mode,$i,$rc,$wall_ms,$det,$to,\"$result_line\",results/raw/${run_id}.log" >> "$CSV"
      printf "  %-13s %-6s run %-3s rc=%-4s wall=%-6sms detected=%s timed_out=%s\n" \
        "$bug" "$mode" "$i" "$rc" "$wall_ms" "$det" "$to"
    done
  done
done

echo "[done] raw logs: $RAW ; summary: $CSV"
python3 scripts/analyze.py
